#!/usr/bin/env python3
"""Eval-cadence planner — prioritize the UNSATURATED marks and stamp BENCHMARKS.md (#2766).

The problem this fixes (operator, #2766): our quality numbers go stale, and the *saturated*
marks (HumanEval, MBPP — frontier all >90%, in every training mix) get re-run more often than
the marks that actually discriminate a small local model's progress (SWE-bench, LongMemEval
end-to-end, honesty F1). A benchmark review should therefore always spend the next run on the
mark that is (a) unsaturated AND (b) most stale — highest information per hour — not on whatever
is easiest to re-run.

This script reads the eval ledgers, computes per-mark freshness, RANKS what to run next by that
rule, and (with --stamp) writes an idempotent freshness block into docs/BENCHMARKS.md so the
quality picture is never more than a build or two old. It does NOT run the heavy harnesses
itself (SWE-bench needs Docker, LongMemEval a dataset, honesty an API key — none guaranteed on a
given box); it tells you which to run and surfaces staleness. `--run` prints the exact command
for the top mark rather than guessing at infra it may not have.

Pure ranking (rank_marks) is ts-agnostic — it takes (saturated, age_days) — so it is unit-tested
independently of the fragile per-ledger timestamp extraction. See tests/test_eval_cadence.py.
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import re
from datetime import datetime, timezone

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BENCHMARKS_MD = os.path.join(REPO, "docs", "BENCHMARKS.md")
BLOCK_BEGIN = "<!-- eval-cadence:begin (generated by scripts/eval_cadence.py — do not edit by hand) -->"
BLOCK_END = "<!-- eval-cadence:end -->"

# The external-mark registry. `saturated` marks are regression tripwires, not differentiators
# (frontier >90%, in training mixes); `unsaturated` marks are where a small local model's real
# progress shows. `run_cmd` is the exact harness invocation an operator/CI should use.
MARKS = [
    {"key": "swebench-lite", "label": "SWE-bench Lite (% resolved)", "saturated": False,
     "run_cmd": "python scripts/eval_swebench_chat.py --provider ollama --limit 20 --grade"},
    {"key": "longmemeval", "label": "LongMemEval (recall@k, end-to-end)", "saturated": False,
     "run_cmd": "LONGMEMEVAL_PATH=/path/to/longmemeval_s.json python experiments/longmemeval_harness.py --k 5"},
    {"key": "honesty", "label": "Honesty / HaluEval gated (F1)", "saturated": False,
     "run_cmd": "python experiments/halueval_gated.py"},
    {"key": "humaneval-chat", "label": "HumanEval chat (pass@1)", "saturated": True,
     "run_cmd": "python scripts/eval_humaneval_chat.py --provider ollama --full"},
    {"key": "humaneval", "label": "HumanEval raw-Ouro (pass@1)", "saturated": True,
     "run_cmd": ".venv-train/Scripts/python scripts/eval_humaneval_ouro.py --full"},
    {"key": "coding", "label": "MBPP / coding-golden (accuracy)", "saturated": True,
     "run_cmd": "python scripts/eval_coding.py --label ouro-fast --model lantern-sigma0-coder"},
]

# A mark this stale is "critically stale" regardless of saturation — used only for the label.
CRITICAL_AGE_DAYS = 14


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _epoch_to_dt(v):
    """Interpret v as unix-epoch SECONDS if it is a plausible recent epoch (> ~2001), else None.
    Ledger rows carry a mix of real epochs and non-timestamp small integers (e.g. a wall-seconds
    duration stamped in `ts`); only accept values that are actually calendar timestamps."""
    try:
        n = float(v)
    except (TypeError, ValueError):
        return None
    if n > 1_000_000_000:  # ~2001-09 onward, in seconds
        try:
            return datetime.fromtimestamp(n, tz=timezone.utc)
        except (OverflowError, OSError, ValueError):
            return None
    return None


def _parse_iso(v):
    if not isinstance(v, str):
        return None
    try:
        return datetime.fromisoformat(v.replace("Z", "+00:00"))
    except ValueError:
        return None


def _newest_leaderboard_ts(benchmark: str):
    """Newest calendar timestamp among leaderboard rows for a given `benchmark` value."""
    path = os.path.join(REPO, "data", "eval", "leaderboard.jsonl")
    newest = None
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            key = r.get("benchmark") or ("coding" if "accuracy" in r else None)
            if key != benchmark:
                continue
            dt = _epoch_to_dt(r.get("ts")) or _parse_iso(r.get("timestamp") or r.get("date"))
            if dt and (newest is None or dt > newest):
                newest = dt
    return newest


def _newest_longmemeval_ts():
    path = os.path.join(REPO, "data", "longmemeval", "runs.jsonl")
    newest = None
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                r = json.loads(line)
            except json.JSONDecodeError:
                continue
            dt = _parse_iso(r.get("timestamp") or r.get("ts"))
            if dt and (newest is None or dt > newest):
                newest = dt
    return newest


def _newest_swebench_ts():
    """SWE-bench predictions are files named ...-<epoch>.jsonl; newest by the trailing epoch."""
    newest = None
    for p in glob.glob(os.path.join(REPO, "data", "eval", "swebench", "*.jsonl")):
        m = re.search(r"-(\d{10})\D", os.path.basename(p) + ".")
        if m:
            dt = _epoch_to_dt(m.group(1))
            if dt and (newest is None or dt > newest):
                newest = dt
    return newest


def _newest_honesty_ts():
    """Honesty/HaluEval result JSONs: use the file mtime (they are overwritten per run)."""
    newest = None
    for name in ("halueval_gated_results.json", "halueval_ab_results.json"):
        p = os.path.join(REPO, "data", "eval", name)
        if os.path.exists(p):
            dt = datetime.fromtimestamp(os.path.getmtime(p), tz=timezone.utc)
            if newest is None or dt > newest:
                newest = dt
    return newest


def mark_freshness(mark: dict):
    """(newest_dt or None, age_days or None) for a registry mark, best-effort per ledger."""
    key = mark["key"]
    if key in ("humaneval", "humaneval-chat", "coding", "swebench-lite"):
        dt = _newest_swebench_ts() if key == "swebench-lite" else _newest_leaderboard_ts(key)
    elif key == "longmemeval":
        dt = _newest_longmemeval_ts()
    elif key == "honesty":
        dt = _newest_honesty_ts()
    else:
        dt = None
    age = None if dt is None else max(0.0, (_now() - dt).total_seconds() / 86400.0)
    return dt, age


def rank_marks(marks):
    """Order marks by information-per-run: UNSATURATED first, then most STALE first.

    Each mark is a dict with `saturated` (bool) and `age_days` (float or None). A mark that has
    NEVER been run (age None) is maximally stale — a missing unsaturated number is the most
    action-guiding line on the board, so it sorts to the very top of its saturation class.
    Pure and ts-agnostic so it can be unit-tested without touching the ledgers."""
    def sort_key(m):
        never = m.get("age_days") is None
        age = float("inf") if never else float(m["age_days"])
        # saturated last (True→1 sorts after False→0); within a class, larger age first (negate)
        return (1 if m.get("saturated") else 0, -age)

    return sorted(marks, key=sort_key)


def build_rows():
    rows = []
    for m in MARKS:
        dt, age = mark_freshness(m)
        rows.append({
            "key": m["key"], "label": m["label"], "saturated": m["saturated"],
            "run_cmd": m["run_cmd"], "newest": dt, "age_days": age,
        })
    return rank_marks(rows)


def _fmt_age(age):
    if age is None:
        return "never run"
    if age < 1:
        return "today"
    return f"{int(round(age))}d"


def render_plan(rows) -> str:
    lines = []
    lines.append("**Eval cadence — run next (unsaturated + most-stale first):**")
    lines.append("")
    lines.append("| # | Mark | Class | Freshness | Priority |")
    lines.append("|---|---|---|---|---|")
    for i, r in enumerate(rows, 1):
        cls = "saturated (tripwire)" if r["saturated"] else "**unsaturated**"
        age = r["age_days"]
        if r["saturated"]:
            pr = "low (re-run only as a regression check)"
        elif age is None:
            pr = "**HIGHEST — never measured**"
        elif age >= CRITICAL_AGE_DAYS:
            pr = f"**HIGH — {int(round(age))}d stale**"
        else:
            pr = "fresh"
        lines.append(f"| {i} | {r['label']} | {cls} | {_fmt_age(age)} | {pr} |")
    top = next((r for r in rows if not r["saturated"]), rows[0] if rows else None)
    if top:
        lines.append("")
        lines.append(f"**Run next:** `{top['run_cmd']}`  \n_(top unsaturated mark: {top['label']}, {_fmt_age(top['age_days'])})_")
    return "\n".join(lines)


def render_block(rows) -> str:
    stamp = _now().strftime("%Y-%m-%d")
    return f"{BLOCK_BEGIN}\n\n_Eval cadence auto-review **{stamp}** (scripts/eval_cadence.py). " \
           f"Freshness read from the ledgers; run order prioritizes unsaturated marks._\n\n" \
           f"{render_plan(rows)}\n\n{BLOCK_END}"


def stamp_benchmarks(rows) -> bool:
    """Insert/replace the managed freshness block in docs/BENCHMARKS.md. Idempotent."""
    if not os.path.exists(BENCHMARKS_MD):
        print(f"[eval-cadence] {BENCHMARKS_MD} not found; nothing to stamp")
        return False
    with open(BENCHMARKS_MD, "r", encoding="utf-8") as f:
        text = f.read()
    block = render_block(rows)
    if BLOCK_BEGIN in text and BLOCK_END in text:
        new = re.sub(re.escape(BLOCK_BEGIN) + r".*?" + re.escape(BLOCK_END), lambda _m: block, text, flags=re.S)
    else:
        # Insert after the first blank line following the H1 title, above the curated review line.
        lines = text.splitlines(keepends=True)
        insert_at = 1
        for i, ln in enumerate(lines):
            if ln.startswith("# "):
                insert_at = i + 1
                break
        lines.insert(insert_at, "\n" + block + "\n")
        new = "".join(lines)
    if new == text:
        print("[eval-cadence] BENCHMARKS.md already current; no change")
        return False
    with open(BENCHMARKS_MD, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print(f"[eval-cadence] stamped freshness block into {BENCHMARKS_MD}")
    return True


def main(argv=None):
    ap = argparse.ArgumentParser(description="Eval-cadence planner (#2766)")
    ap.add_argument("--stamp", action="store_true", help="write the freshness block into docs/BENCHMARKS.md")
    ap.add_argument("--json", action="store_true", help="emit the ranked plan as JSON")
    ap.add_argument("--run", action="store_true", help="print the exact command for the top-priority mark")
    args = ap.parse_args(argv)

    rows = build_rows()

    if args.json:
        print(json.dumps([{**r, "newest": r["newest"].isoformat() if r["newest"] else None} for r in rows], indent=1))
        return 0

    print(render_plan(rows))
    top = next((r for r in rows if not r["saturated"]), None)
    if args.run and top:
        print("\n" + top["run_cmd"])
    if args.stamp:
        stamp_benchmarks(rows)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
