#!/usr/bin/env node
/**
 * check-doc-catalog — fail when the Knowledge Center's source of truth has drifted
 * from what's actually in the repo.
 *
 * The motivating incident: the catalog is the only thing that decides what appears on
 * the public docs surface, but nothing checked it. Fifty-one docs accumulated with no
 * entry — including five ADRs and both Σ₀ whitepapers — and the generator quietly
 * published them with a scraped first line and an "Unreviewed" badge, meaning any file
 * landing in docs/ auto-published itself to unisona.ai with nobody having read it.
 * Meanwhile the committed HTML was 48 cards behind the catalog because nobody re-ran
 * the generator. Both failures were invisible.
 *
 * Fails on:
 *   1. a docs/*.md (or root doc) with no catalog entry
 *   2. a catalog entry whose file no longer exists
 *   3. an entry missing a required field, or carrying an unknown audience/action
 *   4. the committed knowledgecenter.html being out of date w.r.t. the catalog
 *   5. an audience:public doc that names infra we don't publish (origin IPs)
 *
 * Run: node scripts/check-doc-catalog.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG = path.join(REPO, 'data', 'knowledge', 'doc-catalog.json');
const KC_HTML = path.join(REPO, 'apps', 'lantern-garage', 'public', 'knowledgecenter.html');

const CORE = new Set(['README.md', 'CLAUDE.md', 'AGENTS.md', 'QUICKSTART.md']);
// Generated by build_doc_library.js — it must NOT have a catalog entry (it would
// duplicate the research-notes rollup card that points at it).
const GENERATED = new Set(['docs/research/INDEX.md']);
const REQUIRED = ['path', 'title', 'description', 'category', 'status', 'action', 'audience'];
const AUDIENCES = new Set(['public', 'builder', 'internal']);
const ACTIONS = new Set(['keep', 'archive', 'merge', 'remove', 'review']);

const problems = [];

function walk(dir, rel = '') {
  const out = [];
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    const r = rel ? rel + '/' + e.name : e.name;
    if (e.isDirectory()) {
      if (e.name === 'archive' || e.name === 'node_modules' || e.name.startsWith('.')) continue;
      out.push(...walk(path.join(dir, e.name), r));
    } else if (/\.md$/i.test(e.name)) out.push(r);
  }
  return out;
}

const catalog = JSON.parse(fs.readFileSync(CATALOG, 'utf8'));
const byPath = new Map(catalog.map((e) => [e.path, e]));

// 1 + 2 — coverage in both directions
const onDisk = new Set([
  ...fs.readdirSync(REPO).filter((f) => /\.md$/i.test(f) && !CORE.has(f)),
  ...walk(path.join(REPO, 'docs'), 'docs'),
]);
for (const rel of onDisk) {
  if (GENERATED.has(rel)) continue;
  if (!byPath.has(rel)) {
    problems.push(`uncatalogued doc: ${rel}\n    → add an entry to data/knowledge/doc-catalog.json ` +
      `(title, description, category, status, action, audience). Until then it is NOT published.`);
  }
}
for (const e of catalog) {
  const abs = path.join(REPO, e.path);
  if (!fs.existsSync(abs)) problems.push(`catalog entry points at a missing file: ${e.path}`);
}

// 3 — schema
for (const e of catalog) {
  for (const f of REQUIRED) {
    if (!e[f]) problems.push(`${e.path}: missing required field "${f}"`);
  }
  if (e.audience && !AUDIENCES.has(e.audience)) {
    problems.push(`${e.path}: unknown audience "${e.audience}" (expected ${[...AUDIENCES].join('/')})`);
  }
  if (e.action && !ACTIONS.has(e.action)) {
    problems.push(`${e.path}: unknown action "${e.action}" (expected ${[...ACTIONS].join('/')})`);
  }
}

// 4 — the committed page must match what the generator would produce right now
try {
  const before = fs.readFileSync(KC_HTML, 'utf8');
  execFileSync(process.execPath, [path.join(REPO, 'scripts', 'build_doc_library.js')], { stdio: 'pipe' });
  const after = fs.readFileSync(KC_HTML, 'utf8');
  if (before !== after) {
    fs.writeFileSync(KC_HTML, before, 'utf8');   // leave the tree as we found it
    problems.push('knowledgecenter.html is stale relative to the catalog\n' +
      '    → run: node scripts/build_doc_library.js   (and commit the result)');
  }
} catch (err) {
  problems.push('could not verify the generated library: ' + (err.message || err));
}

// 5 — a public doc must not hand out infrastructure detail. Origin IPs are the case
//     that actually happened: the GCE runbook published the address behind Cloudflare.
const IPV4 = /\b(?!0\.|127\.|255\.)(?:\d{1,3}\.){3}\d{1,3}\b/g;
for (const e of catalog) {
  if (e.audience !== 'public' || e.action !== 'keep') continue;
  let body;
  try { body = fs.readFileSync(path.join(REPO, e.path), 'utf8'); } catch { continue; }
  // Private, loopback and link-local ranges are not origin disclosure. 169.254.169.254
  // in particular is the well-known cloud metadata endpoint — it shows up in SSRF
  // hardening notes and names nothing of ours.
  const PRIVATE = /^(?:10\.|127\.|0\.|169\.254\.|192\.168\.|172\.(?:1[6-9]|2\d|3[01])\.)/;
  const hits = [...new Set((body.match(IPV4) || []).filter((ip) => !PRIVATE.test(ip)))];
  if (hits.length) {
    problems.push(`${e.path} is audience:public but names an IP address (${hits.slice(0, 3).join(', ')})\n` +
      `    → move it to audience:internal, or remove the address.`);
  }
}

if (problems.length) {
  console.error(`\n✗ doc catalog check failed (${problems.length}):\n`);
  for (const p of problems) console.error('  • ' + p);
  console.error('');
  process.exit(1);
}
console.log(`✓ doc catalog: ${catalog.length} entries, all files present, page in sync.`);
